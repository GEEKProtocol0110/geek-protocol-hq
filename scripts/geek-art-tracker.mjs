import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = process.cwd();
const read = path => JSON.parse(readFileSync(resolve(root, path), 'utf8'));
const folder = 'docs/continuity/founding/';
const roster = read(folder + 'geek-roster-500.json');
const inventory = read(folder + 'character-art-sets.json');
const legacy = read('public/data/legacy-geek-art.json');
const tiers = inventory.tiers;
assert.equal(roster.entries.length, 500);
assert.equal(new Set(tiers).size, 5);
assert.equal(inventory.plannedCharacterConcepts * tiers.length, 2500);
const nameCounts = new Map();
for (const row of roster.entries) nameCounts.set(row.name, (nameCounts.get(row.name) || 0) + 1);
const supplied = inventory.sets.map(set => ({ ...set, data: read(set.index) }));
const assetIds = new Set();
for (const set of supplied) {
  assert.deepEqual(set.data.records.map(r => r.suppliedTier || r.visibleTier), tiers);
  for (const r of set.data.records) {
    assert.ok(!assetIds.has(r.assetId)); assetIds.add(r.assetId);
  }
}
const assigned = new Set();
const rows = roster.entries.map(row => {
  const matches = supplied.filter(set => set.data.historicalRelations?.rosterSourceId === row.sourceId);
  assert.ok(matches.length <= 1, `Multiple sets assigned to ${row.sourceId}`);
  if (matches.length) {
    assert.equal(row.name, matches[0].character);
    assigned.add(matches[0].index);
  }
  const records = matches[0]?.data.records || [];
  return {
    sourceId: row.sourceId, sourceOrdinal: row.sourceOrdinal, sourceName: row.name,
    sourceLine: row.sourceLine, groupId: row.groupId,
    nameReconciliation: nameCounts.get(row.name) > 1 ? 'repeated-source-label' : 'not-yet-canonicalized',
    canonicalCharacterId: null, nftEdition: null,
    tiers: Object.fromEntries(tiers.map(tier => {
      const found = records.filter(r => (r.suppliedTier || r.visibleTier) === tier);
      return [tier, { state: found.length ? 'original-preserved-unreviewed' : 'availability-unverified',
        assetIds: found.map(r => r.assetId), generatedAsset: null, approved: false }];
    })),
    legacyReferenceIds: legacy.records.filter(r => r.character === row.name).map(r => r.id)
  };
});
const unassignedSets = supplied.filter(s => !assigned.has(s.index)).map(s => ({
  character: s.character, index: s.index, assetIds: s.data.records.map(r => r.assetId),
  reason: 'No historical roster source relationship; preserve without inventing a source or edition mapping.'
}));
const covered = rows.filter(r => Object.values(r.tiers).every(t => t.assetIds.length === 1)).length;
const linkedImages = rows.reduce((n, r) => n + Object.values(r.tiers).reduce((m, t) => m + t.assetIds.length, 0), 0);
assert.equal(rows.length * tiers.length, 2500);
assert.equal(new Set(rows.map(r => r.sourceId)).size, 500);
assert.equal(assetIds.size, inventory.suppliedArtOriginalCount);
assert.equal(linkedImages + unassignedSets.reduce((n, s) => n + s.assetIds.length, 0), assetIds.size);
const report = {
  schema: 1, founderDecision: 'DR-012', sourceRoster: folder + 'geek-roster-500.json',
  purpose: 'Planning positions, not approved canonical character IDs or NFT editions.',
  tiers, plannedCharacterConcepts: 500, plannedArtworkSlots: 2500,
  summary: { sourcePositions: 500, exactDistinctSourceNames: nameCounts.size,
    repeatedNameGroups: [...nameCounts.values()].filter(n => n > 1).length,
    suppliedCompleteSets: supplied.length, suppliedArtOriginals: assetIds.size,
    sourceLinkedCompleteSets: covered, sourceLinkedOriginals: linkedImages,
    unassignedOriginals: assetIds.size - linkedImages,
    sourceSlotsWithUnverifiedAvailability: 2500 - linkedImages,
    generatedHere: 0, approved: 0 },
  statePolicy: {
    'availability-unverified': 'No linked received original. More founder files may exist; this is not proof artwork must be generated.',
    'original-preserved-unreviewed': 'Exact received source is archived; canonical placement and final art approval are unfinished.',
    legacyReferences: 'Potential reference art only. Do not count it as a completed tier or regenerate over it without review.',
    generatedHere: 'No new art was generated by preparing this tracker. Generated assets require separately recorded files and provenance.'
  },
  unassignedSets, rows
};
const safe = value => String(value).replaceAll('|', '\\|').replaceAll('<', '&lt;');
const status = tier => tier.assetIds.length ? tier.assetIds.join(', ') : 'Unverified';
const md = '# Geek artwork production tracker\n\nGenerated by `node scripts/geek-art-tracker.mjs --write`. [Production workflow](GEEK-ART-PRODUCTION.md).\n\n' +
  '**500 planned characters × five rarity artworks = 2,500 planned images.** Rows preserve historical source positions; repeated labels and unresolved canonical IDs remain visible.\n\n' +
  `Received: **${supplied.length} complete sets / ${assetIds.size} originals**. Historical-source links: ${covered} complete sets / ${linkedImages} originals. ${assetIds.size - linkedImages} originals remain unassigned to source positions. Generated here: 0. Approved: 0.\n\n` +
  '**Unverified means availability is unknown**, not missing forever or automatically ready for generation. Legacy references are separate. [Machine-readable tracker](art/artwork-production.json).\n\n' +
  '## Unassigned supplied sets\n\n' + unassignedSets.map(s => `- ${safe(s.character)}: ${s.assetIds.join(', ')}. Canonical placement unresolved.`).join('\n') + '\n\n' +
  '| Source | Character label | Common | Rare | Epic | Legendary | Mythic | Source-name review | Legacy references |\n| --- | --- | --- | --- | --- | --- | --- | --- | --- |\n' +
  rows.map(r => `| ${r.sourceId} | ${safe(r.sourceName)} | ${tiers.map(t => status(r.tiers[t])).join(' | ')} | ${r.nameReconciliation} | ${r.legacyReferenceIds.join(', ') || 'None indexed'} |`).join('\n') + '\n';
const outputs = [['docs/art/artwork-production.json', JSON.stringify(report, null, 2) + '\n'], ['docs/GEEK-ART-PROGRESS.md', md]];
for (const [path, text] of outputs) {
  if (process.argv.includes('--write')) writeFileSync(resolve(root, path), text);
  else assert.equal(readFileSync(resolve(root, path), 'utf8'), text, `Stale ${path}; regenerate tracker`);
}
console.log(JSON.stringify(report.summary));
